window.Witness = (function () {
  "use strict";

  var GROUPS = [
    /* 关于看 */
    ["从这个角度看，你最先注意到的是哪里？",
     "如果往后退一步，这个世界看起来会有什么不一样？",
     "有没有哪个角落，让你想再多看一眼？",
     "如果视线可以在这个世界里走一圈，它会从哪里开始？"],

    /* 关于它本身 */
    ["如果这个世界会说话，它想说什么？",
     "这里什么最有力量？什么最安静？",
     "有没有什么东西，是你一开始没打算放进去的？",
     "这个世界里，哪一处是你最后放下的？",
     "如果把这里看作一个地方，它是什么天气？"],

    /* 关于你 */
    ["摆放的时候，哪一下最犹豫？",
     "这个世界里，你最想待在哪里？",
     "如果这里可以再多一个人，会是谁？",
     "有哪个位置，是你反复挪动过的？",
     "现在，你的身体有什么感觉？"],

    /* 关于时间 */
    ["如果这个世界再过一天，会发生什么？",
     "有没有什么，是你想从这里带走的？",
     "如果它可以变得不一样，你会动哪一处？",
     "如果把这个世界留给谁看，你会想让他看到什么？"],
  ];

  var pool = [];
  function refill() {
    pool = [];
    GROUPS.forEach(function (g) { g.forEach(function (q) { pool.push(q); }); });
    // 洗牌
    for (var i = pool.length - 1; i > 0; i--) {
      var j = Math.floor(Math.random() * (i + 1));
      var t = pool[i]; pool[i] = pool[j]; pool[j] = t;
    }
  }
  refill();

  /* 抽一句，尽量不重复，用完自动重洗 */
  function pick() {
    if (!pool.length) refill();
    return pool.pop();
  }

  return { pick: pick, total: GROUPS.reduce(function (n, g) { return n + g.length; }, 0) };
})();
